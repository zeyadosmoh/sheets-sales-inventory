/**
 * setupWorkbook(): builds every sheet, formulas, validation, protection, charts,
 * and seeds deterministic synthetic sample data.
 *
 * Safe by default: on a file that already has content it asks for confirmation,
 * and refuses when no UI is available (e.g. run from the editor).
 */

var HEADER_BG = '#1f4e79';
var SALES_SPARE_ROWS = 1000;

function setupWorkbook() {
  var ss = ss_();
  if (workbookHasContent_(ss)) {
    var ui = tryGetUi_();
    if (!ui) {
      throw new Error('This file already has content. To rebuild it (this deletes ALL data), open the spreadsheet and use Shop Tools > Rebuild workbook.');
    }
    var answer = ui.alert('Rebuild workbook?',
      'This DELETES every sheet and all data in this file, then recreates them with synthetic sample data. Continue?',
      ui.ButtonSet.YES_NO);
    if (answer !== ui.Button.YES) return;
  }
  buildWorkbook_(ss);
}

/** Sheets from older versions; always removed by a rebuild. */
var LEGACY_SHEETS = ['Invoice_Template'];

/**
 * Final sweep after a rebuild: delete legacy sheets (e.g. the hidden
 * Invoice_Template from the old sheet-export invoice) and anything else that is
 * not one of ours, so a rebuild always leaves a clean file.
 */
function removeUnknownSheets_(ss) {
  var ours = Object.keys(SHEET).map(function (k) { return SHEET[k]; });
  ss.getSheets().forEach(function (sh) {
    var name = sh.getName();
    if (ours.indexOf(name) === -1 || LEGACY_SHEETS.indexOf(name) !== -1) {
      console.log('Rebuild: removing sheet "' + name + '"');
      ss.deleteSheet(sh);
    }
  });
}

/** True if any of our sheets exist or any sheet has data. */
function workbookHasContent_(ss) {
  return ss.getSheets().some(function (sh) {
    return sh.getLastRow() > 0 || Object.keys(SHEET).some(function (k) { return SHEET[k] === sh.getName(); });
  });
}

function buildWorkbook_(ss) {
  ss.setSpreadsheetTimeZone(SCRIPT_TIMEZONE);

  // A spreadsheet must always keep one sheet, so park a temporary one while deleting.
  var temp = ss.insertSheet('_setup_tmp_' + new Date().getTime());
  ss.getSheets().forEach(function (sh) {
    if (sh.getSheetId() !== temp.getSheetId()) ss.deleteSheet(sh);
  });

  var settings = defaultSettings();
  var data = generateSeedData();

  var dash = ss.insertSheet(SHEET.DASHBOARD, 0);
  // Products first: the Sales SKU dropdown and lookups point at it.
  buildProductsSheet_(ss.insertSheet(SHEET.PRODUCTS, 1), data.products, settings);
  buildSalesSheet_(ss.insertSheet(SHEET.SALES, 1), data.sales, settings);
  buildInventorySheet_(ss.insertSheet(SHEET.INVENTORY, 3), data.inventory);
  buildImportSheet_(ss.insertSheet(SHEET.IMPORT, 4));
  buildImportLogSheet_(ss.insertSheet(SHEET.IMPORT_LOG, 5));
  buildSettingsSheet_(ss.insertSheet(SHEET.SETTINGS, 6), settings);
  ss.deleteSheet(temp);
  removeUnknownSheets_(ss);

  buildDashboardSheet_(dash, settings);
  SpreadsheetApp.flush();
  refreshDashboard_();
  buildDashboardCharts_(dash);
  protectRange_(dash.getRange('A1:L60'), 'Dashboard is generated by Shop Tools > Refresh dashboard', true);

  ss.setActiveSheet(dash);
  ss.toast('Workbook built with ' + data.products.length + ' products and ' + data.sales.length +
    ' sales lines (' + SAMPLE_DATA_LABEL.toLowerCase() + ').', 'Shop Tools', 8);
}

/* ---------- shared helpers ---------- */

function writeHeader_(sh, headers) {
  sh.getRange(1, 1, 1, headers.length).setValues([headers])
    .setFontWeight('bold').setBackground(HEADER_BG).setFontColor('#ffffff');
  sh.setFrozenRows(1);
}

/** Keep only the columns we use, so the sheets look tidy. */
function trimColumns_(sh, keep) {
  var max = sh.getMaxColumns();
  if (max > keep) sh.deleteColumns(keep + 1, max - keep);
}

/**
 * Protect a range. Default: only the owner can edit.
 * warningOnly: everyone can edit after a warning (used where scripts run as any editor).
 */
function protectRange_(range, description, warningOnly) {
  var p = range.protect().setDescription(description);
  if (warningOnly) return p.setWarningOnly(true);
  p.removeEditors(p.getEditors());
  if (p.canDomainEdit()) p.setDomainEdit(false);
  return p;
}

/* ---------- Products ---------- */

function buildProductsSheet_(sh, products, settings) {
  writeHeader_(sh, HEADERS.PRODUCTS);
  trimColumns_(sh, HEADERS.PRODUCTS.length);
  sh.getRange(2, 1, products.length, 6).setValues(products.map(function (p) {
    return [p.sku, p.name, p.category, p.cost, p.price, p.reorderLevel];
  }));
  var rows = sh.getMaxRows() - 1;
  sh.getRange(2, 4, rows, 2).setNumberFormat(currencyFormat_(settings.currency));

  sh.getRange(2, 1, rows, 1).setDataValidation(SpreadsheetApp.newDataValidation()
    .requireFormulaSatisfied('=COUNTIF($A:$A,A2)=1').setAllowInvalid(false)
    .setHelpText('SKU must be unique.').build());
  sh.getRange(2, 4, rows, 2).setDataValidation(SpreadsheetApp.newDataValidation()
    .requireNumberGreaterThanOrEqualTo(0).setAllowInvalid(false).setHelpText('Enter a number >= 0.').build());
  sh.getRange(2, 6, rows, 1).setDataValidation(SpreadsheetApp.newDataValidation()
    .requireFormulaSatisfied('=AND(ISNUMBER(F2),F2>=0,INT(F2)=F2)').setAllowInvalid(false)
    .setHelpText('Reorder level is a whole number >= 0.').build());

  sh.getRange(1, 1, products.length + 1, 6).applyRowBanding(SpreadsheetApp.BandingTheme.LIGHT_GREY, true, false);
  sh.setColumnWidths(1, 1, 90);
  sh.setColumnWidth(2, 220);
  sh.setColumnWidths(3, 4, 110);
}

/* ---------- Sales ---------- */

function buildSalesSheet_(sh, sales, settings) {
  writeHeader_(sh, HEADERS.SALES);
  trimColumns_(sh, HEADERS.SALES.length);
  ensureRows_(sh, sales.length + SALES_SPARE_ROWS);
  appendSalesRaw_(sh, sales, 'seed');

  // Formula columns (one ARRAYFORMULA each, protected).
  sh.getRange('D2').setFormula('=ARRAYFORMULA(IF(C2:C="","",IFERROR(VLOOKUP(C2:C,Products!A2:B,2,FALSE),"Unknown SKU")))');
  sh.getRange('G2').setFormula('=ARRAYFORMULA(IF((C2:C="")+(E2:E="")+(F2:F=""),"",ROUND(E2:E*F2:F,2)))');

  var rows = sh.getMaxRows() - 1;
  sh.getRange(2, 1, rows, 1).setNumberFormat('yyyy-mm-dd');
  sh.getRange(2, 6, rows, 2).setNumberFormat(currencyFormat_(settings.currency));

  sh.getRange(2, 1, rows, 1).setDataValidation(SpreadsheetApp.newDataValidation()
    .requireDate().setAllowInvalid(false).setHelpText('Enter a valid date.').build());
  sh.getRange(2, 3, rows, 1).setDataValidation(SpreadsheetApp.newDataValidation()
    .requireValueInRange(sh.getParent().getSheetByName(SHEET.PRODUCTS).getRange('A2:A'), true)
    .setAllowInvalid(false).setHelpText('Pick a SKU from the Products sheet.').build());
  sh.getRange(2, 5, rows, 1).setDataValidation(SpreadsheetApp.newDataValidation()
    .requireFormulaSatisfied('=AND(ISNUMBER(E2),E2>0,INT(E2)=E2)').setAllowInvalid(false)
    .setHelpText('Quantity is a whole number > 0.').build());

  protectRange_(sh.getRange('D:D'), 'Sales: Product is a formula');
  protectRange_(sh.getRange('G:G'), 'Sales: Total is a formula');
  protectRange_(sh.getRange('A1:I1'), 'Sales: header');

  sh.getRange('A1').setNote(SAMPLE_DATA_LABEL + '. Unit Price fills automatically when you pick a SKU.');
  sh.setColumnWidth(1, 95); sh.setColumnWidth(2, 125); sh.setColumnWidth(3, 85); sh.setColumnWidth(4, 200);
  sh.setColumnWidths(5, 1, 60); sh.setColumnWidths(6, 2, 110); sh.setColumnWidth(8, 150); sh.setColumnWidth(9, 140);
}

/** Bulk write used during setup (sheet object passed in, no lookups). */
function appendSalesRaw_(sh, sales, source) {
  var n = sales.length;
  sh.getRange(2, 1, n, 3).setValues(sales.map(function (s) { return [isoToDate_(s.date), s.invoice, s.sku]; }));
  sh.getRange(2, 5, n, 2).setValues(sales.map(function (s) { return [s.qty, s.unitPrice]; }));
  sh.getRange(2, 8, n, 2).setValues(sales.map(function (s) { return [s.customer, source]; }));
}

/* ---------- Inventory ---------- */

function buildInventorySheet_(sh, inventory) {
  writeHeader_(sh, HEADERS.INVENTORY);
  trimColumns_(sh, HEADERS.INVENTORY.length);
  sh.getRange(2, 1, inventory.length, 1).setValues(inventory.map(function (r) { return [r.sku]; }));
  sh.getRange(2, 3, inventory.length, 2).setValues(inventory.map(function (r) { return [r.opening, r.purchases]; }));

  // Same rules as computeOnHand() / inventoryStatus() in src/lib/Inventory.js.
  sh.getRange('B2').setFormula('=ARRAYFORMULA(IF(A2:A="","",IFERROR(VLOOKUP(A2:A,Products!A2:B,2,FALSE),"Unknown SKU")))');
  sh.getRange('E2').setFormula('=ARRAYFORMULA(IF(A2:A="","",SUMIF(Sales!C2:C,A2:A,Sales!E2:E)))');
  sh.getRange('F2').setFormula('=ARRAYFORMULA(IF(A2:A="","",C2:C+D2:D-E2:E))');
  sh.getRange('G2').setFormula('=ARRAYFORMULA(IF(A2:A="","",IFERROR(VLOOKUP(A2:A,Products!A2:F,6,FALSE),0)))');
  sh.getRange('H2').setFormula('=ARRAYFORMULA(IF(A2:A="","",IF(F2:F<0,"OVERSOLD",IF(F2:F=0,"OUT",IF(F2:F<=G2:G,"LOW","OK")))))');

  var rows = sh.getMaxRows() - 1;
  sh.getRange(2, 3, rows, 2).setDataValidation(SpreadsheetApp.newDataValidation()
    .requireFormulaSatisfied('=AND(ISNUMBER(C2),C2>=0)').setAllowInvalid(false)
    .setHelpText('Stock quantities are numbers >= 0.').build());

  var status = sh.getRange(2, 8, rows, 1);
  sh.setConditionalFormatRules([
    SpreadsheetApp.newConditionalFormatRule().whenTextEqualTo(STATUS.OVERSOLD)
      .setBackground('#b3261e').setFontColor('#ffffff').setBold(true).setRanges([status]).build(),
    SpreadsheetApp.newConditionalFormatRule().whenTextEqualTo(STATUS.OUT)
      .setBackground('#f4c7c3').setFontColor('#b3261e').setBold(true).setRanges([status]).build(),
    SpreadsheetApp.newConditionalFormatRule().whenTextEqualTo(STATUS.LOW)
      .setBackground('#fce8b2').setFontColor('#8a5300').setBold(true).setRanges([status]).build(),
    SpreadsheetApp.newConditionalFormatRule().whenTextEqualTo(STATUS.OK)
      .setBackground('#d9ead3').setFontColor('#274e13').setRanges([status]).build()
  ]);

  ['B:B', 'E:E', 'F:F', 'G:G', 'H:H'].forEach(function (a1) {
    protectRange_(sh.getRange(a1), 'Inventory: ' + a1.charAt(0) + ' is a formula');
  });
  sh.getRange('A1').setNote('On Hand = Opening Stock + Purchases - Sold. Status: OVERSOLD < 0 (check purchases/opening stock), OUT = 0, LOW <= Reorder Level, else OK.');
  sh.setColumnWidth(1, 90); sh.setColumnWidth(2, 220); sh.setColumnWidths(3, 6, 105);
}

/* ---------- Import, Import_Log ---------- */

function buildImportSheet_(sh) {
  writeHeader_(sh, HEADERS.IMPORT);
  trimColumns_(sh, HEADERS.IMPORT.length);
  sh.getRange(2, 1, sh.getMaxRows() - 1, HEADERS.IMPORT.length).setNumberFormat('@'); // keep pasted text as-is
  sh.getRange('A1').setNote('Paste raw sales rows below the header (any date format, Arabic-Indic digits OK), ' +
    'then use Shop Tools > Import from "Import" sheet. Required: Date, SKU, Qty.');
  sh.setColumnWidths(1, 5, 140);
}

